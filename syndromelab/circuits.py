"""Stim circuits for the rotated surface code memory experiment under several noise models."""
from __future__ import annotations

import stim

TASK = "surface_code:rotated_memory_z"
_MEASURE = {"M", "MR", "MX", "MRX"}
_RESET = {"R", "MR", "RX", "MRX"}
_ANNOTATION = {"DETECTOR", "OBSERVABLE_INCLUDE", "SHIFT_COORDS", "QUBIT_COORDS"}
_ONE_QUBIT = {"H"}
_TWO_QUBIT = {"CX", "CZ"}


def noiseless(distance: int, rounds: int, task: str = TASK) -> stim.Circuit:
    return stim.Circuit.generated(task, distance=distance, rounds=rounds)


def si1000(distance: int, rounds: int, p: float, task: str = TASK) -> stim.Circuit:
    """SI1000 rates (Gidney et al. 2021) applied to Stim's CX-based surface code circuit.

    two-qubit gate: DEPOLARIZE2(p) | one-qubit gate: DEPOLARIZE1(p/10)
    reset: X_ERROR(2p) | measurement: result flipped with probability 5p
    idle during gates: DEPOLARIZE1(p/10) | idle during measurement/reset: DEPOLARIZE1(2p)
    """
    base = noiseless(distance, rounds, task).flattened()
    all_qubits = sorted(base.get_final_qubit_coordinates().keys())
    out = stim.Circuit()
    moment: list[stim.CircuitInstruction] = []

    def flush() -> None:
        touched: set[int] = set()
        has_mr = False
        for op in moment:
            name = op.name
            if name in _ANNOTATION:
                out.append(op)
                continue
            qs = [t.value for t in op.targets_copy()]
            touched.update(qs)
            if name in _MEASURE:
                has_mr = True
                out.append(name, qs, 5 * p)
            else:
                out.append(op)
            if name in _RESET:
                has_mr = True
                out.append("Z_ERROR" if name.endswith("X") else "X_ERROR", qs, 2 * p)
            elif name in _ONE_QUBIT:
                out.append("DEPOLARIZE1", qs, p / 10)
            elif name in _TWO_QUBIT:
                out.append("DEPOLARIZE2", qs, p)
            elif name not in _MEASURE:
                raise ValueError(f"unsupported instruction {name}")
        if touched:
            idle = [q for q in all_qubits if q not in touched]
            if idle:
                out.append("DEPOLARIZE1", idle, 2 * p if has_mr else p / 10)
        moment.clear()

    for op in base:
        if op.name == "TICK":
            flush()
            out.append("TICK")
        else:
            moment.append(op)
    flush()
    return out


def sd(distance: int, rounds: int, p: float, task: str = TASK) -> stim.Circuit:
    """Uniform circuit-level depolarizing noise, as generated by Stim (all four knobs = p)."""
    return stim.Circuit.generated(
        task, distance=distance, rounds=rounds,
        after_clifford_depolarization=p, before_round_data_depolarization=p,
        before_measure_flip_probability=p, after_reset_flip_probability=p)


def code_capacity(distance: int, p_flip: float) -> stim.Circuit:
    """Independent X flips on data qubits, perfect syndrome measurement, one round."""
    base = noiseless(distance, 1).flattened()
    data = None
    for op in base:
        if op.name == "M":
            data = [t.value for t in op.targets_copy()]
    out = stim.Circuit()
    first_tick = True
    for op in base:
        out.append(op)
        if op.name == "TICK" and first_tick:
            out.append("X_ERROR", data, p_flip)
            first_tick = False
    return out


NOISE = {"si1000": si1000, "sd": sd}


def make(noise: str, distance: int, rounds: int, p: float) -> stim.Circuit:
    return NOISE[noise](distance, rounds, p)
